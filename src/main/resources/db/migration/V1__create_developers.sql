CREATE TABLE developers
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name        VARCHAR(80)          NOT NULL,
    last_name         VARCHAR(80)          NOT NULL,
    email             VARCHAR(180)         NOT NULL UNIQUE,
    github_username   VARCHAR(39)          NOT NULL UNIQUE,
    level             VARCHAR(20)          NOT NULL CHECK (level IN
                      ('FRESHER', 'INTERN', 'JUNIOR', 'MID_LEVEL', 'SENIOR', 'STAFF', 'PRINCIPAL')),
    team              VARCHAR(20)          NOT NULL CHECK (team IN
                      ('PLATFORM', 'BACKEND', 'FRONTEND', 'FULL_STACK', 'DEVOPS', 'MOBILE', 'DATA', 'QA', 'SECURITY')),
    status            VARCHAR(20)          NOT NULL CHECK (status IN ('ACTIVE', 'ON_LEAVE', 'INACTIVE')),
    progress_percent  SMALLINT             NOT NULL CHECK (progress_percent BETWEEN 0 AND 100),
    experience_years  NUMERIC(4, 1)         NOT NULL CHECK (experience_years >= 0),
    joined_on         DATE                 NOT NULL,
    last_active_at    TIMESTAMPTZ          NOT NULL DEFAULT NOW(),
    mentor_id         BIGINT REFERENCES developers (id) ON DELETE SET NULL,
    bio               VARCHAR(1000),
    created_at        TIMESTAMPTZ          NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ          NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_developers_level ON developers (level);
CREATE INDEX idx_developers_team ON developers (team);
CREATE INDEX idx_developers_status ON developers (status);
CREATE INDEX idx_developers_last_active ON developers (last_active_at DESC);
CREATE INDEX idx_developers_mentor ON developers (mentor_id);
